import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { internalIdsFor } from '../src/block-registry.js';

const research = new URL('../public/research/', import.meta.url);
const registry = JSON.parse(await readFile(new URL('block-registry-1.7.10.json', research)));
const shadows = JSON.parse(await readFile(new URL('shadow-reference.json', research)));
assert.equal(registry.blocks.length, registry.count);
assert.equal(new Set(registry.blocks.map((b) => b.id)).size, registry.count);
const mapped = new Map([[0, [0]]]);
for (const [internal, block] of Object.entries(shadows.blocks)) {
  const ids = mapped.get(block.mc) || [];
  ids.push(Number(internal));
  mapped.set(block.mc, ids);
}
// Explicitly merged flowing/still representations; not additional native blocks.
mapped.set(8, [10]);
mapped.set(10, [42]);
// The port's own registry (src/block-registry.js, the chunk-store id mapping) is the primary mapping and covers every
// block added after the shadow probes; the shadow-probe mapping stays as a cross-check so a probe-mapped id never
// disappears.
const rows = registry.blocks.map(({ id, name }) => {
  const own = internalIdsFor(id);
  const probe = mapped.get(id) ?? [];
  const internal = [...new Set([...own, ...probe])].sort((a, b) => a - b);
  return `| ${id} | ${name} | ${internal.length ? internal.join(', ') : '—'} | ${internal.length ? 'Partial; browser block mapped, behavior audit required (see [metadata audit](block-metadata-catalogue.md))' : 'Missing; no browser block'} |`;
});
await writeFile(new URL('block-parity-catalogue.md', research), `# Original base-block parity catalogue

Generated by \`node tools/build-parity-catalogue.mjs\` from the original registry, the port's block registry (\`src/block-registry.js\`) and the existing shadow-probe ID mapping. Includes all ${registry.count} base registrations, including technical blocks. See [roadmap](parity-roadmap.md).

This is an exhaustive base-ID inventory, **not** an exhaustive behavior or metadata checklist. A mapping proves a browser representation exists, not full parity. As of the batch 19 audit every one of the 171 registrations maps to at least one browser block; Missing would mean none exists. No row is certified fully verified. Metadata expansion and per-feature acceptance/evidence remain next tasks; do not hand-edit this generated file.

Every row requires placement/metadata, bounds/collision/rays, support and neighbor updates, scheduled/random ticks, light/rendering, mining/harvest/drops, recipes/acquisition, sound, persistence and cross-system acceptance checks as applicable. Variant families (wood, saplings, leaves, wool, flowers, slabs, stairs, crops, fluids) require separate variant cases.

| Java ID | Registry name | Browser internal IDs | Status |
| --- | --- | --- | --- |
${rows.join('\n')}
`);
console.log(`Wrote ${registry.count} original base-block rows; metadata and behavior audits remain open.`);
