// Seed atlas: which short seeds put villages, temples and swamp huts in the finite world
// (chunks [origin, origin+8) on both axes), near the streamed spawn, plus the first stronghold.
// Pure JS: only StructurePopulation's native search (MapGenStructure.generate) is used.
// Usage: node tools/find-structure-seeds.mjs [firstSeed=0] [lastSeed=200] [--write]
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { WorldChunkManager, } from "../src/biome-layers.js";
import { BIOMES_TO_SPAWN_IN } from "../src/biome-layers.js";
import { JavaRandom } from "../src/java-random.js";
import { StructurePopulation } from "../src/structure-population.js";
import { DesertPyramid, JunglePyramid, SwampHut } from "../src/scattered-feature-generator.js";

const args = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const first = Number(args[0] ?? 0), last = Number(args[1] ?? 200), write = process.argv.includes("--write");
const RADIUS = 512;
const kindOf = (s) => {
  const c = s.components[0];
  return c instanceof DesertPyramid ? "desert temple" : c instanceof JunglePyramid ? "jungle temple" : c instanceof SwampHut ? "swamp hut" : "?";
};

export function atlasForSeed(n) {
  const seed = BigInt(n), manager = new WorldChunkManager(seed, "default");
  const spawn = manager.findBiomePosition(0, 0, 256, BIOMES_TO_SPAWN_IN, new JavaRandom(seed));
  const spawnChunk = [spawn ? spawn[0] >> 4 : 0, spawn ? spawn[2] >> 4 : 0];
  const origin = [spawnChunk[0] - 4, spawnChunk[1] - 4];
  // The streamed view centres on local block (64,64): origin + 64.
  const spawnBlock = [origin[0] * 16 + 64, origin[1] * 16 + 64];
  const pop = new StructurePopulation({ worldSeed: seed, manager, world: { rand: new JavaRandom(0n) } });
  for (let x = origin[0]; x < origin[0] + 8; x++) for (let z = origin[1]; z < origin[1] + 8; z++) pop.searchChunk(x, z);
  for (const dx of [-34, -17, 0, 17, 34]) for (const dz of [-34, -17, 0, 17, 34]) pop.searchChunk(spawnChunk[0] + dx, spawnChunk[1] + dz);
  const rows = [];
  for (const name of ["village", "scatteredFeature"]) for (const s of pop.generators[name].structureMap.values()) {
    if (!s.isSizeableStructure()) continue;
    const kind = name === "village" ? "village" : kindOf(s), bx = s.chunkX * 16 + 8, bz = s.chunkZ * 16 + 8;
    rows.push({ kind, chunk: [s.chunkX, s.chunkZ], block: [bx, bz], distance: Math.round(Math.hypot(bx - spawnBlock[0], bz - spawnBlock[1])),
      inWorld: s.chunkX >= origin[0] && s.chunkX < origin[0] + 8 && s.chunkZ >= origin[1] && s.chunkZ < origin[1] + 8,
      biome: manager.biomeAt(bx, bz).name ?? manager.biomeAt(bx, bz).slot, size: s.components.length });
  }
  const [sx, sz] = pop.generators.stronghold.positions[0];
  return { seed: n, origin, spawnBlock, rows, stronghold: { chunk: [sx, sz], block: [sx * 16 + 8, sz * 16 + 8] } };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const kinds = ["village", "desert temple", "jungle temple", "swamp hut"], atlas = [];
  for (let n = first; n <= last; n++) atlas.push(atlasForSeed(n));
  const out = [];
  const line = (s) => { out.push(s); if (!write) console.log(s); };
  line(`# Structure seed atlas (generated by tools/find-structure-seeds.mjs, seeds ${first}-${last})`);
  line("");
  line("Seeds use generation chunk-manager type default. Origin is the finite/streamed world origin chunk (spawn chunk minus 4); the finite world covers chunks [origin, origin+8) on both axes (128x128 blocks). Streamed spawn is approximated as origin block + 64 (the view centre); the real spawn is a dry column nearby. Coordinates are block X,Z at the start chunk centre (chunk*16+8). Only sizeable starts are listed (village needs more than 2 non-road pieces).");
  line("");
  for (const kind of kinds) {
    line(`## ${kind}`);
    line("");
    const inside = atlas.map((a) => ({ a, r: a.rows.filter((r) => r.kind === kind && r.inWorld) })).filter((e) => e.r.length);
    line(`Seeds with a start inside the finite world (${inside.length}):`);
    line("");
    line("| seed | origin chunk | start block X,Z | start chunk | biome | pieces |");
    line("|---|---|---|---|---|---|");
    for (const { a, r } of inside) for (const s of r) line(`| ${a.seed} | ${a.origin} | ${s.block} | ${s.chunk} | ${s.biome} | ${s.size} |`);
    line("");
    const near = atlas.map((a) => ({ a, r: a.rows.filter((r) => r.kind === kind && r.distance <= RADIUS).sort((p, q) => p.distance - q.distance)[0] })).filter((e) => e.r)
      .sort((p, q) => p.r.distance - q.r.distance);
    line(`Nearest to the streamed spawn within ${RADIUS} blocks (${near.length} seeds, closest 15):`);
    line("");
    line("| seed | spawn block X,Z | start block X,Z | distance | biome |");
    line("|---|---|---|---|---|");
    for (const { a, r } of near.slice(0, 15)) line(`| ${a.seed} | ${a.spawnBlock} | ${r.block} | ${r.distance} | ${r.biome} |`);
    line("");
  }
  line("## First stronghold");
  line("");
  line("| seed | stronghold chunk | block X,Z (chunk centre) | distance from streamed spawn |");
  line("|---|---|---|---|");
  for (const a of atlas) line(`| ${a.seed} | ${a.stronghold.chunk} | ${a.stronghold.block} | ${Math.round(Math.hypot(a.stronghold.block[0] - a.spawnBlock[0], a.stronghold.block[1] - a.spawnBlock[1]))} |`);
  if (write) writeFileSync(fileURLToPath(new URL("../public/research/structure-seeds.md", import.meta.url)), out.join("\n") + "\n");
}
