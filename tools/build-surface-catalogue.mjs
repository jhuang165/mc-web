import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const research = new URL('../public/research/', import.meta.url);
const reference = JSON.parse(await readFile(new URL('surface-registry-reference.json', research)));
assert.equal(reference.clientSha1, 'e80d9b3bf5085002218d4be59e668bac718abbc6');
const { commands, profiles, screens, guiSupport, structureStarts, structurePieces, mapGenerators, features } = reference;
assert.deepEqual([commands.length, screens.length, guiSupport.length, structureStarts.length, structurePieces.length, mapGenerators.length, features.length], [48, 58, 66, 5, 48, 10, 41]);
const unique = (rows, key) => assert.equal(new Set(rows.map(r => r[key])).size, rows.length);
for (const rows of [commands, screens, guiSupport, mapGenerators, features]) unique(rows, 'class');
for (const rows of [structureStarts, structurePieces]) unique(rows, 'id');
const short = name => name.replace(/^net\/minecraft\//, '');
const leaf = name => name.split('/').at(-1);
const intro = 'Generated by `node tools/build-surface-catalogue.mjs`; refresh original evidence with `node tools/verify-surface-catalogue.mjs` (JDK, pinned client JAR, MCP SRG names and local libraries). [Roadmap](parity-roadmap.md) · [original evidence and provenance](surface-registry-reference.json). Enumeration does not certify whole-feature parity.';

const commandRows = commands.map(c => `| /${c.name} | ${c.aliases.map(a => '/' + a).join(', ') || '—'} | ${c.scope} | ${c.permissionLevel}${c.customPermission ? '; custom check' : ''} | ${c.usage} | ${short(c.mappedName)} | Missing command system | Q |`);
const profileRows = [];
for (const p of profiles) {
  unique(p.lookup, 'key');
  const registrations = commands.filter(c => c.scope === 'common' || c.scope === p.profile);
  for (const c of registrations) assert(p.lookup.some(r => r.key === c.name && r.class === c.class));
  for (const entry of p.lookup) {
    assert(registrations.some(c => c.class === entry.class && (c.name === entry.key || c.aliases.includes(entry.key))));
    profileRows.push(`| ${p.profile} | /${entry.key} | /${entry.name} | ${entry.class} | Native registration lookup only | Q |`);
  }
}
