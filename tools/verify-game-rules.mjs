// Finds every GameRules read in the 1.7.10 client JAR: each method whose bytecode loads a rule name with ldc (javap -c),
// named through the MCP joined.srg and the table below, and writes public/research/game-rules-reference.json with the
// port's status of each call site for src/game-rules.test.js. Needs a JDK and the pinned client JAR (tools/research or
// MC_RESEARCH); joined-1.7.10.srg comes from the same directory.
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdir, readFile, writeFile, access, rm, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createHash } from "node:crypto";
import assert from "node:assert/strict";

const exec = promisify(execFile),
  root = path.dirname(fileURLToPath(import.meta.url)),
  exists = (p) => access(p).then(() => true, () => false);
const researchDirs = [process.env.MC_RESEARCH, path.join(root, "research"), path.join(root, "../../tools/research")].filter(Boolean);
let research;
for (const dir of researchDirs) if (await exists(path.join(dir, "minecraft-1.7.10.jar"))) { research = dir; break; }
if (!research) throw new Error("Place minecraft-1.7.10.jar in tools/research or set MC_RESEARCH.");
const jar = path.join(research, "minecraft-1.7.10.jar"), clientSha1 = "e80d9b3bf5085002218d4be59e668bac718abbc6";
assert.equal(createHash("sha1").update(await readFile(jar)).digest("hex"), clientSha1);
const RULES = ["commandBlockOutput", "doDaylightCycle", "doFireTick", "doMobLoot", "doMobSpawning", "doTileDrops", "keepInventory", "mobGriefing", "naturalRegeneration"];

// The port's handling of each native call site (class.method -> [status, where]). status: wired (the port checks the rule
// there), absent (the feature is not in this build), registry (GameRules itself).
const PORT = {
  "GameRules.<init>": ["registry", "src/command-data.js GAME_RULES (generated by tools/verify-commands.mjs)"],
  "BlockFire.updateTick": ["wired", "src/fire.js updateTick (L.fireTick)"],
  "EntityLightningBolt.<init>": ["wired", "src/fire.js boltStart"],
  "EntityLightningBolt.onUpdate": ["wired", "src/fire.js boltRestrike"],
  "BlockPortal.updateTick": ["absent", "no zombie pigmen: portals never spawn mobs in this build"],
  "WorldServer.tick": ["wired", "src/entities.js tick (the night spawn ring)"],
  "BlockFarmland.onFallenUpon": ["wired", "src/farming.js trample (grief), main.js trampleFarmland"],
  "EntityLiving.onLivingUpdate": ["absent", "mobs never pick up items in this build"],
  "EntityAIBreakDoor.shouldExecute": ["absent", "the zombie break-door task is not run"],
  "EntityAIEatGrass.updateTask": ["wired", "src/entities.js eatGrass"],
  "EntityDragon.destroyBlocksInAABB": ["absent", "no ender dragon"],
  "EntityCreeper.func_146077_cc": ["wired", "src/entities.js creeper explode event (smoking), src/explosion-simulation.js"],
  "EntitySilverfish.updateEntityActionState": ["wired", "src/entities.js silverfish env.mobGriefing, src/silverfish.js wake"],
  "EntityEnderman.onLivingUpdate": ["absent", "no enderman AI"],
  "EntityWither.updateAITasks": ["absent", "no wither"],
  "EntityWitherSkull.onImpact": ["absent", "no wither skulls"],
  "EntityLargeFireball.onImpact": ["absent", "no ghast fireballs"],
  "EntityLivingBase.onDeathUpdate": ["wired", "src/entities.js deathUpdate; main.js player death orbs"],
  "EntityLivingBase.onDeath": ["wired", "src/entities.js onDeath"],
  "EntityAIMate.spawnBaby": ["wired", "src/entities.js spawnBaby"],
  "ServerCommandManager.func_152372_a": ["absent", "no command blocks"],
  "Block.dropBlockAsItem_do": ["wired", "main.js items.dropBlock wrapper"],
  "EntityPlayer.getExperiencePoints": ["wired", "main.js death (keepInventory)"],
  "EntityPlayer.onDeath": ["wired", "main.js death (keepInventory)"],
  "EntityPlayerMP.onDeath": ["wired", "main.js death (keepInventory: no inventory drop)"],
  "EntityPlayer.clonePlayer": ["wired", "main.js respawn (keepInventory: inventory and experience kept)"],
  "FoodStats.onUpdate": ["wired", "src/survival.js tick (food regeneration)"],
  "EntityPlayer.onLivingUpdate": ["wired", "src/survival.js tick (Peaceful regeneration)"],
  "WorldServer.tick#doDaylightCycle": ["wired", "src/survival.js tick (timeFrozen)"],
  "WorldClient.tick": ["wired", "src/survival.js tick (one clock: the client and server time are the same object here)"],
  "WorldClient.func_72877_b": ["wired", "src/survival.js timeFrozen (the client's setWorldTime sign flag has no packet here)"],
  "ServerConfigurationManager.func_72354_b": ["wired", "src/survival.js timeFrozen (the S03 time packet's frozen flag has no packet here)"],
};
// MCP srg method names to readable ones (joined.srg has only func_ names).
const NAMES = {
  func_149674_a: "updateTick", func_70071_h_: "onUpdate", func_72835_b: "tick", func_149746_a: "onFallenUpon",
  func_70636_d: "onLivingUpdate", func_75250_a: "shouldExecute", func_75246_d: "updateTask", func_70972_a: "destroyBlocksInAABB",
  func_70626_be: "updateEntityActionState", func_70619_bc: "updateAITasks", func_70227_a: "onImpact", func_70609_aI: "onDeathUpdate",
  func_70645_a: "onDeath", func_75388_i: "spawnBaby", func_149642_a: "dropBlockAsItem_do", func_70693_a: "getExperiencePoints",
  func_71049_a: "clonePlayer", func_75118_a: "onUpdate", func_82764_b: "addGameRule",
};

const work = path.join(research, "game-rules-probe");
await rm(work, { recursive: true, force: true });
await mkdir(work, { recursive: true });
await exec("unzip", ["-q", "-o", jar, "*.class", "-x", "net/*", "-d", work], { maxBuffer: 1 << 24 });
const srg = await readFile(path.join(research, "joined-1.7.10.srg"), "utf8");
const classNames = new Map(), methodNames = new Map();
for (const line of srg.split("\n")) {
  let m = /^CL: (\S+) (\S+)/.exec(line);
  if (m) { classNames.set(m[1], m[2].split("/").pop()); continue; }
  m = /^MD: (\S+)\/(\S+) (\S+) \S+\/(\S+) \S+/.exec(line);
  if (m) methodNames.set(`${m[1]}.${m[2]}${m[3]}`, m[4]);
}
const files = (await readdir(work)).filter((f) => f.endsWith(".class"));
const sites = [];
for (const file of files) {
  const bytes = await readFile(path.join(work, file));
  if (!RULES.some((r) => bytes.includes(r))) continue;
  const obf = file.slice(0, -6);
  const { stdout } = await exec("javap", ["-c", "-p", "-s", path.join(work, file)], { maxBuffer: 1 << 26 });
  let method = null, descriptor = null;
  for (const line of stdout.split("\n")) {
    const head = /^  (?:[\w$<>\[\]., ]+ )?([\w$<>]+)\(.*\);$/.exec(line);
    if (head) { method = head[1] === obf ? "<init>" : head[1]; descriptor = null; continue; }
    const d = /^    descriptor: (\S+)/.exec(line);
    if (d) { descriptor = d[1]; continue; }
    const s = /ldc(?:_w)?\s+#\d+\s+\/\/ String (\w+)$/.exec(line);
    if (!s || !RULES.includes(s[1]) || !method) continue;
    const cls = classNames.get(obf) ?? obf, srgName = method === "<init>" || method === "<clinit>" ? method : methodNames.get(`${obf}.${method}${descriptor}`) ?? method;
    sites.push({ rule: s[1], obf: `${obf}.${method}${descriptor}`, cls, method: NAMES[srgName] ?? srgName });
  }
}
// One row per (rule, class, method), with the number of reads.
const rows = new Map();
for (const s of sites) {
  const key = `${s.rule} ${s.cls}.${s.method}`;
  rows.set(key, { ...s, reads: (rows.get(key)?.reads ?? 0) + 1 });
}
const out = [...rows.values()].sort((a, b) => (a.rule + a.cls + a.method).localeCompare(b.rule + b.cls + b.method)).map((r) => {
  const site = `${r.cls}.${r.method}`, port = PORT[`${site}#${r.rule}`] ?? PORT[site];
  return { rule: r.rule, site, obf: r.obf, reads: r.reads, port: port?.[0] ?? "unknown", where: port?.[1] ?? "" };
});
const unknown = out.filter((r) => r.port === "unknown");
assert.equal(unknown.length, 0, "unmapped call sites: " + unknown.map((r) => r.rule + " " + r.site).join(", "));
for (const r of out) console.log(r.rule.padEnd(20), r.site.padEnd(48), r.reads, r.port);
await writeFile(path.join(root, "../public/research/game-rules-reference.json"), JSON.stringify({
  target: "Minecraft Java 1.7.10", clientSha1, method: "javap -c over every JAR class holding a rule name; ldc sites per method, named through joined-1.7.10.srg",
  rules: RULES, sites: out,
}, null, 1) + "\n");
await rm(work, { recursive: true, force: true });
