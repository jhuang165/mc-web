// Reads ItemStack.getDisplayName of every registered original item/block-item and damage subtype through
// tools/probes/ItemNameProbe.java (real StringTranslate over the JAR's en_US.lang) and writes
// public/research/item-names-reference.json for src/item-names.test.js. Needs a JDK, the pinned client JAR and the guava /
// log4j-api / commons-lang3 / netty-all JARs.
