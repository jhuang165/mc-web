// Generates src/bidi-data.js from the ICU4J 51.2 classes of the 1.7.10 client libraries (icu4j-core-mojang-51.2.jar, the Bidi and
// ArabicShaping FontRenderer.bidiReorder calls). tools/probes/FontStyleProbe.java prints the BMP bidi classes, mirror pairs
// (UBiDiProps, the data ICU4J Bidi.writeReordered mirrors with) and the unchanged ArabicShaping(LETTERS_SHAPE) output for every
// candidate character alone and next to a dual-joining BEH; this script folds that into the compact tables bidi.js uses.
// Needs a JDK, the pinned client JAR (MC_RESEARCH) and the extracted classes the other font probes use (tools/verify-sign-font.mjs).
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { runProbe } from "./font-style-probe.mjs";

const root = path.dirname(fileURLToPath(import.meta.url));
const data = JSON.parse(await runProbe("data"));
const shape = (await runProbe("shape")).trim().split("\n");

const classes = data.classes.split(",").slice(0, 65536).map(Number);
const runs = [];
for (let i = 0, prev = -1; i < 65536; i++) if (classes[i] !== prev) { runs.push(i, classes[i]); prev = classes[i]; }
const mirror = data.mirror.split(",").filter(Boolean).flatMap((p) => p.split(":").map(Number));

const h = (s) => parseInt(s, 16);
const chars = [];
const lig = {};
for (const line of shape) {
  const parts = line.split(" ");
  if (parts[0].startsWith("L")) {
    // lam + alef: [alone, after BEH, ...] the ligature (isolated) and its final form
    if (parts[1].length !== 4) continue; // lam + alef wasla etc. is not ligated
    const f1 = parts[2];
    lig[h(parts[0].slice(1))] = [h(parts[1]), h(f1.slice(4))];
    continue;
  }
  const [c, f0, f1, f2, f3, f4] = parts;
  const plain = f0 === c && f1 === "fe8f" + c && f2 === c + "fe8f" && f3 === "fe8f" + c + "fe8f" && f4 === "fe8f" + c + "fe76fe8f";
  if (plain) continue;
  const joinPrev = f1.startsWith("fe91"), joinNext = f2.endsWith("fe90");
  const transparent = !joinPrev && !joinNext && f3.startsWith("fe91") && f3.endsWith("fe90");
  const one = (s) => { if (s.length !== 4) throw new Error(`form of ${c} is not one code unit: ${s}`); return h(s); };
  chars.push([h(c), one(f0), joinPrev ? one(f1.slice(4)) : 0, joinNext ? one(f2.slice(0, -4)) : 0, (joinPrev && joinNext) || transparent ? one(f3.slice(4, -4)) : 0, (joinPrev ? 1 : 0) | (joinNext ? 2 : 0) | (transparent ? 4 : 0)]);
}
const wrap = (a, n = 24) => a.reduce((s, v, i) => s + (i % n === 0 ? "\n  " : " ") + v + ",", "");
const out = `// Generated by tools/gen-bidi-data.mjs from the ICU4J 51.2 data of the 1.7.10 client (UBiDiProps and the unchanged ArabicShaping). Do not edit.
// BIDI_CLASS_RUNS: [start, class, ...] over the BMP, classes numbered as ICU UCharacterDirection (0 L, 1 R, 2 EN, 3 ES, 4 ET, 5 AN, 6 CS,
// 7 B, 8 S, 9 WS, 10 ON, 11 LRE, 12 LRO, 13 AL, 14 RLE, 15 RLO, 16 PDF, 17 NSM, 18 BN). BIDI_MIRRORS: [char, mirror, ...].
// SHAPE_CHARS rows: [char, isolated, final, initial, medial, flags] (0 = no such form; flags 1 joins the previous letter, 2 joins the next, 4 is
// transparent: tashkeel and the 206D-206F controls, whose medial form shows when both neighbours connect). SHAPE_LIGATURES: alef -> [lam-alef isolated, final].
export const BIDI_CLASS_RUNS = [${wrap(runs)}
];
export const BIDI_MIRRORS = [${wrap(mirror)}
];
export const SHAPE_CHARS = [${chars.map((r) => "\n  [" + r.join(",") + "],").join("")}
];
export const SHAPE_LIGATURES = ${JSON.stringify(lig)};
`;
await writeFile(path.join(root, "../src/bidi-data.js"), out);
console.log(`bidi-data.js: ${runs.length / 2} class runs, ${mirror.length / 2} mirrors, ${chars.length} shaping rows, ${Object.keys(lig).length} ligatures`);
