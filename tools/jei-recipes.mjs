// Recipe viewer mod (not 1.7.10): writes src/mods/jei/native-recipes.js, the enumerable crafting table the viewer lists.
//
// The browser's crafting code is matchers (craftingResult and the per-family *CraftingResult functions), not a list, so the
// table comes from the native 1.7.10 recipe registry (public/research/recipe-registry-reference.json, CraftingManager's 312
// fixed recipes in original ids). Each recipe's ingredients are converted to browser stacks with the same conversion the
// recipe audit uses (tools/recipe-audit.mjs browserStack), placed in a 3x3 grid and run through the live craftingResult. Only
// recipes the live code crafts are written, with the live result as the output. A wildcard ingredient (damage 32767) lists
// each browser subtype whose grid still crafts the same output, so the viewer can cycle through them.
//
//   node tools/jei-recipes.mjs          rewrite the table
//   node tools/jei-recipes.mjs --check  exit 1 when the table is stale (src/mods-jei-recipes.test.js runs the same check)
import { readFileSync, writeFileSync } from 'node:fs';
import { browserStack } from './recipe-audit.mjs';
import { craftingResult } from '../src/survival.js';

const WILDCARD = 32767;
const reference = () => JSON.parse(readFileSync(new URL('../public/research/recipe-registry-reference.json', import.meta.url)));
const pair = (s) => [s.id, s.damage | 0];
const sameOutput = (a, b) => !!a && !!b && a.id === b.id && a.count === b.count && (a.damage | 0) === (b.damage | 0);

// The native ingredient's browser alternatives: [[id, damage], ...]; [] when it has no browser item.
function alternatives(ing) {
  if (ing.damage !== WILDCARD) { const s = browserStack(ing); return s ? [pair(s)] : []; }
  const out = [];
  for (let d = 0; d < 16; d++) {
    const s = browserStack({ ...ing, damage: d });
    if (s && !out.some(([id, dm]) => id === s.id && dm === (s.damage | 0))) out.push(pair(s));
  }
  return out;
}

const grid = (slots, pick = () => 0) => slots.map((alts, i) => (alts ? { id: alts[pick(i)][0], count: 1, damage: alts[pick(i)][1] } : null));

export function buildNativeRecipes(ref = reference()) {
  const recipes = [], skipped = [];
  for (const r of ref.crafting) {
    if (r.type === 'special') continue; // the five dynamic handlers (dyed armor, fireworks, book and map copies) have no fixed grid
    const shapeless = r.type === 'shapeless', w = shapeless ? 3 : r.width, h = shapeless ? 3 : r.height;
    const native = shapeless ? r.ingredients : Array.from({ length: 9 }, (_, i) => (i % 3 < w && Math.floor(i / 3) < h ? r.ingredients[Math.floor(i / 3) * w + (i % 3)] : null));
    if (native.some((ing) => ing?.tag)) { skipped.push({ index: r.index, reason: 'tag' }); continue; }
    let slots = Array.from({ length: 9 }, (_, i) => (native[i] ? alternatives(native[i]) : null));
    if (slots.some((a) => a && !a.length)) { skipped.push({ index: r.index, reason: 'unmapped ingredient' }); continue; }
    const out = craftingResult(grid(slots), 3);
    if (!out) { skipped.push({ index: r.index, reason: 'not crafted' }); continue; }
    // Keep an alternative only when the grid with it (the other slots at their first choice) crafts the same stack. Slots
    // holding the same native wildcard switch together, as a player fills them with one kind of plank or log.
    slots = slots.map((alts, i) => {
      if (!alts || alts.length < 2) return alts;
      const twins = native.map((ing, j) => (ing && JSON.stringify(ing) === JSON.stringify(native[i]) ? j : -1)).filter((j) => j >= 0);
      return alts.filter((_, k) => k === 0 || sameOutput(craftingResult(grid(slots, (j) => (twins.includes(j) ? k : 0)), 3), out));
    });
    const used = slots.map((a, i) => (a ? i : -1)).filter((i) => i >= 0);
    recipes.push({
      index: r.index,
      shapeless,
      width: shapeless ? 0 : w,
      height: shapeless ? 0 : h,
      // Shaped: the 3x3 grid, row-major, null for empty cells. Shapeless: the ingredients in order.
      slots: shapeless ? used.map((i) => slots[i]) : slots,
      output: { id: out.id, count: out.count, damage: out.damage | 0 },
    });
  }
  return { recipes, skipped };
}

export function nativeRecipesSource(table = buildNativeRecipes()) {
  const lines = table.recipes.map((r) => '  ' + JSON.stringify(r) + ',');
  return `// Generated by tools/jei-recipes.mjs from public/research/recipe-registry-reference.json; do not edit by hand.
// Native 1.7.10 crafting recipes in browser item ids, each checked through the live craftingResult (see the tool's header).
// ${table.recipes.length} recipes; skipped native indices: ${table.skipped.map((s) => `${s.index} (${s.reason})`).join(', ') || 'none'}.
export const NATIVE_RECIPES = [
${lines.join('\n')}
];
`;
}

const target = new URL('../src/mods/jei/native-recipes.js', import.meta.url);
if (import.meta.url === `file://${process.argv[1]}`) {
  const source = nativeRecipesSource();
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8');
    if (current !== source) { console.error('src/mods/jei/native-recipes.js is stale: run node tools/jei-recipes.mjs'); process.exit(1); }
    console.log('native-recipes.js is current');
  } else {
    writeFileSync(target, source);
    console.log(`wrote ${target.pathname}`);
  }
}
