// Runs the unchanged 1.7.10 Stitcher (tools/probes/StitcherProbe.java) over the block and item sprite sets TextureMap registers and writes
// public/research/stitcher-reference.json plus src/atlas-layout.js (the block atlas positions the port lays its tiles out on).
// Needs a JDK, the pinned client JAR (tools/research or MC_RESEARCH) and libs-1.7.10 (or MC_PROBE_LIBS).
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdir, readFile, writeFile, access, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createHash } from "node:crypto";
import assert from "node:assert/strict";

const exec = promisify(execFile), root = path.dirname(fileURLToPath(import.meta.url)), exists = (p) => access(p).then(() => true, () => false);
let research;
for (const dir of [process.env.MC_RESEARCH, path.join(root, "research"), path.join(root, "../../tools/research")].filter(Boolean)) if (await exists(path.join(dir, "minecraft-1.7.10.jar"))) { research = dir; break; }
if (!research) throw new Error("Place minecraft-1.7.10.jar in tools/research or set MC_RESEARCH.");
const jar = path.join(research, "minecraft-1.7.10.jar"), out = path.join(research, "stitcher-probe");
const clientSha1 = "e80d9b3bf5085002218d4be59e668bac718abbc6";
assert.equal(createHash("sha1").update(await readFile(jar)).digest("hex"), clientSha1);
const libDir = process.env.MC_PROBE_LIBS || path.join(research, "libs-1.7.10");
const lib = (name) => path.join(libDir, `${name}.jar`);
await rm(out, { recursive: true, force: true });
const classes = path.join(out, "classes"), probe = path.join(out, "probe");
for (const d of [classes, probe]) await mkdir(d, { recursive: true });
await exec("unzip", ["-q", "-o", jar, "*.class", "-d", classes], { maxBuffer: 1 << 24 });
const cp = [probe, classes, lib("log4j-api-2.0-beta9"), lib("guava-15.0"), lib("commons-lang3-3.1"), lib("commons-io-2.4"), lib("gson-2.2.4")].join(path.delimiter);
await exec("javac", ["-nowarn", "-cp", cp, "-d", probe, path.join(root, "probes/StitcherProbe.java")]);
const { stdout } = await exec("java", ["-Djava.awt.headless=true", `-Djar=${jar}`, "-cp", cp, "StitcherProbe"], { maxBuffer: 1 << 26 });
const runs = stdout.trim().split("\n").filter((l) => l.startsWith("{")).map((l) => JSON.parse(l));
assert.equal(runs.length, 10);
const atlases = {};
for (const type of ["blocks", "items"]) {
  const mine = runs.filter((r) => r.type === type), base = mine[0];
  // The layout must not depend on the mipmap level for sprites of 16 px and 32 px (Stitcher.Holder rounds to multiples of 2^level).
  for (const r of mine) { assert.equal(r.width, base.width); assert.equal(r.height, base.height); assert.deepEqual(r.sprites, base.sprites); }
  atlases[type] = { width: base.width, height: base.height, mipLevelsChecked: mine.map((r) => r.mip), sprites: base.sprites.map(([name, x, y, w, h, minU, maxU, minV, maxV]) => ({ name, x, y, w, h, minU, maxU, minV, maxV })) };
}
await writeFile(path.join(root, "../public/research/stitcher-reference.json"), JSON.stringify({
  source: "tools/verify-stitcher.mjs: unchanged Stitcher (bpv, Holder bpw, Slot bpx) and TextureAtlasSprite.initSprite (bqd) driven as TextureMap.loadTextureAtlas does, over the sprites registered by the executed Block.registerBlockIcons / Item.registerIcons",
  clientSha1, maxTextureSize: 16384, atlases,
}) + "\n");
// The port reads only the block atlas positions: name -> [x, y, size].
const layout = Object.fromEntries(atlases.blocks.sprites.map((s) => [s.name, [s.x, s.y, s.w]]));
await writeFile(path.join(root, "../src/atlas-layout.js"), `// GENERATED by tools/verify-stitcher.mjs from the executed 1.7.10 Stitcher (public/research/stitcher-reference.json): the block atlas
// (TextureMap type 0) is ${atlases.blocks.width} x ${atlases.blocks.height}; each entry is [x, y, size] of a registered sprite, names without the blocks/ prefix.
export const NATIVE_ATLAS_WIDTH = ${atlases.blocks.width}, NATIVE_ATLAS_HEIGHT = ${atlases.blocks.height};
export const NATIVE_BLOCK_SPRITES = ${JSON.stringify(layout)};
`);
// The item atlas (TextureMap type 1, textures/atlas/items.png): name -> [x, y, size], names without the items/ prefix.
const itemLayout = Object.fromEntries(atlases.items.sprites.map((s) => [s.name, [s.x, s.y, s.w]]));
await writeFile(path.join(root, "../src/item-atlas-layout.js"), `// GENERATED by tools/verify-stitcher.mjs from the executed 1.7.10 Stitcher (public/research/stitcher-reference.json): the item atlas
// (TextureMap type 1) is ${atlases.items.width} x ${atlases.items.height}; each entry is [x, y, size] of a registered sprite, names without the items/ prefix.
export const NATIVE_ITEM_ATLAS_WIDTH = ${atlases.items.width}, NATIVE_ITEM_ATLAS_HEIGHT = ${atlases.items.height};
export const NATIVE_ITEM_SPRITES = ${JSON.stringify(itemLayout)};
`);
console.log(`blocks ${atlases.blocks.width}x${atlases.blocks.height} ${atlases.blocks.sprites.length} sprites, items ${atlases.items.width}x${atlases.items.height} ${atlases.items.sprites.length} sprites`);
