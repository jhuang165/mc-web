// Deterministically regenerates public/research/block-metadata-catalogue.md from
// public/research/block-metadata-reference.json (refresh that with tools/verify-block-metadata.mjs)
// and the current browser block registry (src/block-registry.js fromOriginal).
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';

export const CATEGORIES = ['semantic', 'alias', 'invalid', 'unclassified'];

export function ranges(values) {
  const out = [];
  for (let i = 0; i < values.length;) {
    let j = i;
    while (j + 1 < values.length && values[j + 1] === values[j] + 1) j++;
    out.push(j > i + 1 ? `${values[i]}–${values[j]}` : values.slice(i, j + 1).join(', '));
    i = j + 1;
  }
  return out.join(', ');
}

// browser(mcId, meta) -> 'exact' | 'approximate' | 'none' (src/block-registry.js fromOriginal).
export function browserStatus(fromOriginal) {
  return (id, meta) => {
    const r = fromOriginal(id, meta);
    return r ? (r.exact ? 'exact' : 'approximate') : 'none';
  };
}

export function render(reference, browser) {
  const blocks = reference.blocks;
  const tally = Object.fromEntries(CATEGORIES.map(c => [c, 0]));
  const place = {'creative-item': 0, 'item-damage': 0, none: 0};
  const bstat = {exact: 0, approximate: 0, none: 0};
  const rows = blocks.map(b => {
    const cells = CATEGORIES.map(cat => {
      const vs = b.values.filter(v => v.category === cat);
      tally[cat] += vs.length;
      if (cat === 'alias') {
        const by = new Map();
        for (const v of vs) by.set(v.aliasOf, [...(by.get(v.aliasOf) || []), v.meta]);
        return [...by].map(([to, m]) => `${ranges(m)}→${to}`).join('; ') || '—';
      }
      return vs.length ? ranges(vs.map(v => v.meta)) : '—';
    });
    for (const v of b.values) place[v.placement]++;
    const bs = {exact: [], approximate: [], none: []};
    for (let m = 0; m < 16; m++) { const s = browser(b.id, m); bs[s].push(m); bstat[s]++; }
    const bcell = ['exact', 'approximate', 'none'].filter(k => bs[k].length).map(k => `${k} ${bs[k].length === 16 ? 'all 16' : ranges(bs[k])}`).join('; ');
    const creative = b.creativeDamages.length ? b.creativeDamages.map(d => `${b.itemId}:${d}`).join(', ') : '—';
    const placed = b.placedAll.length ? ranges(b.placedAll) : '—';
    const readers = b.bytecode.unprobedMetadataReaders.length;
    return `| ${b.id} | ${b.name} | ${creative} | ${placed} | ${cells.join(' | ')} | ${readers || '—'} | ${bcell} |`;
  });
  const total = blocks.length * 16;
  return `# Original block metadata audit

Generated by \`node tools/build-block-metadata-catalogue.mjs\` from [native metadata classification](block-metadata-reference.json) (refresh with \`node tools/verify-block-metadata.mjs\`; the older scaffold in \`tools/build-content-catalogue.mjs\` no longer writes this file). [Base blocks](block-parity-catalogue.md) · [item subtypes and acceptance gates](item-parity-catalogue.md) · [roadmap](parity-roadmap.md).

All **${blocks.length} block registrations** x 16 raw 4-bit values = **${total} ID/metadata combinations** are classified from the unchanged original 1.7.10 classes (client JAR SHA-1 \`${reference.clientSha1}\`). Totals: **${tally.semantic} semantic**, **${tally.alias} alias**, **${tally.invalid} invalid**, **${tally.unclassified} unclassified**. This is a catalogue of the native storage domain with conservative categories. It does not claim browser behavior parity; the last column only reports whether the browser block registry maps the value.

## Categories and evidence

- **Semantic**: the native probed surface differs from every lower value of the same block (or the block's metadata provably never varies, so value 0 is its single canonical state).
- **Alias**: the probed surface is identical to a lower value (the \`→N\` target) and no override outside the probed surface reads metadata. Treat as "native code cannot tell these apart in the executed methods", not as proof that persistence round-trips must normalize them.
- **Invalid**: a probed original method throws an index/class-cast fault for that value only (native read fault). Not a statement about vanilla placement reachability.
- **Unclassified**: not established. Typical causes: the block overrides tick, neighbor, activation, drop or position-dependent methods that read metadata (bytecode-detected) and were not executed; or a probed method failed on the stub world for a reason not shown to be native.

**Native-executed evidence** (BlockMetadataProbe, headless, one block in an otherwise empty map-backed World double): damageDropped, idDropped, quantityDropped (plain and fortune 3), getIcon for sides 0–5 through a naming icon-register proxy, render type, opaque/normal-cube flags, light value and opacity, map colour, canCollideCheck, setBlockBoundsBasedOnState bounds, collision box, hardness, pick block, getDamageValue, passability, weak/strong power for all six sides, canProvidePower and comparator override; Item.getMetadata plus Block.onBlockPlaced for item damage 0–15 over sides 0–5 and two hit heights. **Bytecode-read evidence** (javap, own class chain and inner classes only): overrides outside that set that call World/IBlockAccess/TileEntity getBlockMetadata, use a metadata argument, or call such a method inside the chain. **Not executed**: entity-based placement (onBlockPlacedBy: stairs, doors, pistons, furnaces, logs placed by look direction), neighbor-dependent bounds/icons, scheduled/random ticks, activation, tile entity state, redstone propagation, fluid flow, persistence.

Columns: **Creative stacks** are \`item:damage\` from native getSubBlocks (item damage, not world metadata); **Item-placed** are metadata values produced by onBlockPlaced from any item damage 0–15; **Unprobed readers** counts distinct unprobed metadata-reading overrides (see JSON \`bytecode\`); **Browser mapping** counts values with an exact, approximate (fallback) or no mapping in \`fromOriginal\` today (${bstat.exact} exact, ${bstat.approximate} approximate, ${bstat.none} none of ${total}). Placement across all values: ${place['creative-item']} reachable from Creative item damage, ${place['item-damage']} only from other item damage, ${place.none} not produced by item placement (they may still arise from world generation, updates or commands).

| Java block ID | Registry name | Creative stacks | Item-placed | Semantic | Alias (→canonical) | Invalid | Unclassified | Unprobed readers | Browser mapping |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const research = new URL('../public/research/', import.meta.url);
  const reference = JSON.parse(await readFile(new URL('block-metadata-reference.json', research)));
  const {fromOriginal} = await import('../src/block-registry.js');
  await writeFile(new URL('block-metadata-catalogue.md', research), render(reference, browserStatus(fromOriginal)));
  console.log(`Wrote block metadata catalogue for ${reference.blocks.length} blocks.`);
}
