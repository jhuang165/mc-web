// Deterministically regenerates public/research/block-metadata-catalogue.md from
// public/research/block-metadata-reference.json (refresh that with tools/verify-block-metadata.mjs)
// and the current browser block registry (src/block-registry.js fromOriginal).
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';

export const CATEGORIES = ['semantic', 'alias', 'invalid', 'unclassified'];

export function ranges(values) {
  const out = [];
  for (let i = 0; i < values.length;) {
    let j = i;
    while (j + 1 < values.length && values[j + 1] === values[j] + 1) j++;
    out.push(j > i + 1 ? `${values[i]}–${values[j]}` : values.slice(i, j + 1).join(', '));
    i = j + 1;
  }
  return out.join(', ');
}

// browser(mcId, meta) -> 'exact' | 'approximate' | 'none' (src/block-registry.js fromOriginal).
export function browserStatus(fromOriginal) {
  return (id, meta) => {
    const r = fromOriginal(id, meta);
    return r ? (r.exact ? 'exact' : 'approximate') : 'none';
  };
}

export function render(reference, browser) {
  const blocks = reference.blocks;
  const tally = Object.fromEntries(CATEGORIES.map(c => [c, 0]));
  const place = {'creative-item': 0, 'item-damage': 0, none: 0};
  const bstat = {exact: 0, approximate: 0, none: 0};
  const rows = blocks.map(b => {
    const cells = CATEGORIES.map(cat => {
      const vs = b.values.filter(v => v.category === cat);
      tally[cat] += vs.length;
      if (cat === 'alias') {
        const by = new Map();
        for (const v of vs) by.set(v.aliasOf, [...(by.get(v.aliasOf) || []), v.meta]);
        return [...by].map(([to, m]) => `${ranges(m)}→${to}`).join('; ') || '—';
      }
      return vs.length ? ranges(vs.map(v => v.meta)) : '—';
    });
    for (const v of b.values) place[v.placement]++;
    const bs = {exact: [], approximate: [], none: []};
    for (let m = 0; m < 16; m++) { const s = browser(b.id, m); bs[s].push(m); bstat[s]++; }
    const bcell = ['exact', 'approximate', 'none'].filter(k => bs[k].length).map(k => `${k} ${bs[k].length === 16 ? 'all 16' : ranges(bs[k])}`).join('; ');
    const creative = b.creativeDamages.length ? b.creativeDamages.map(d => `${b.itemId}:${d}`).join(', ') : '—';
    const placed = b.placedAll.length ? ranges(b.placedAll) : '—';
    const readers = (b.bytecode.unexecutedMetadataReaders || b.bytecode.unprobedMetadataReaders).length;
    return `| ${b.id} | ${b.name} | ${creative} | ${placed} | ${cells.join(' | ')} | ${readers || '—'} | ${bcell} |`;
  });
  const total = blocks.length * 16;
  return `# Original block metadata audit

Generated by \`node tools/build-block-metadata-catalogue.mjs\` from [native metadata classification](block-metadata-reference.json) (refresh with \`node tools/verify-block-metadata.mjs\`; the older scaffold in \`tools/build-content-catalogue.mjs\` no longer writes this file). [Base blocks](block-parity-catalogue.md) · [item subtypes and acceptance gates](item-parity-catalogue.md) · [roadmap](parity-roadmap.md).

All **${blocks.length} block registrations** x 16 raw 4-bit values = **${total} ID/metadata combinations** are classified from the unchanged original 1.7.10 classes (client JAR SHA-1 \`${reference.clientSha1}\`). Totals: **${tally.semantic} semantic**, **${tally.alias} alias**, **${tally.invalid} invalid**, **${tally.unclassified} unclassified**. This is a catalogue of the native storage domain with conservative categories. It does not claim browser behavior parity; the last column only reports whether the browser block registry maps the value.

## Categories and evidence

- **Semantic**: a conclusive native outcome (probed or executed, no exception or nondeterminism) differs from every lower value of the same block, or the block's class chain never distinguishes values, so its lowest value is the single canonical state.
- **Alias**: every probed and executed outcome is identical to a lower semantic value (the \`→N\` target), none of them is an exception or nondeterministic, every metadata-reading override of the class chain was executed conclusively, the block creates no tile entity and its RenderBlocks render method does not read metadata. Treat as "native code cannot tell these apart in the executed methods and samples", not as proof that persistence round-trips must normalize them.
- **Invalid**: an original method (probed or executed) throws an index/class-cast fault in game code for that value only. Not a statement about vanilla placement reachability.
- **Unclassified**: not established. Typical causes: a metadata reader that was not executed conclusively (tile-entity state, a RenderBlocks render method, a failure on the World/player doubles, nondeterminism), outcomes that differ only by an own-item stack damage or in fields where one side failed, or an identical surface to a value that is itself not established. Each value records its reason in the JSON.

**Probed evidence** (BlockMetadataProbe, headless, one block in an otherwise empty map-backed World double): damageDropped, idDropped, quantityDropped (plain and fortune 3), getIcon for sides 0–5 through a naming icon-register proxy, render type, opaque/normal-cube flags, light value and opacity, map colour, canCollideCheck, setBlockBoundsBasedOnState bounds, collision box, hardness, pick block, getDamageValue, passability, weak/strong power for all six sides, canProvidePower and comparator override; Item.getMetadata plus Block.onBlockPlaced for item damage 0–15 over sides 0–5 and two hit heights.

**Executed evidence** (BlockMetadataExtProbe): ${(reference.executedMethods || []).length} distinct World/IBlockAccess-taking method signatures declared in block class chains (ticks, random display ticks, neighbor changes, onBlockAdded, breakBlock, harvest/drop, activation, placement, collision boxes and ray traces, colour/icon queries and others), plus Block.dropBlockAsItemWithChance and createStackedBlock, in four layouts (${(reference.executedScenarios || []).join(', ')}: air around, stone around, neighbours of the same block and value, value 0 surrounded by the value). Methods whose outcome depends on neighbouring copies also run the full centre x neighbour metadata matrix. Random arguments and World.rand use seeds 0–2 plus all-lowest and all-highest draws; player arguments are a player double holding nothing, its own item, a flower, a water bucket, a glass bottle or bone meal. Outcomes are return values, written cells, recorded World side effects and the held stack, each run twice; metadata carried in outcomes is compared by its class in a joint partition over all blocks. These are samples, not proof over every world state.

**Bytecode evidence** (javap): overrides of the block's own class chain and inner classes that call World/IBlockAccess/TileEntity getBlockMetadata, use a metadata argument, or call such a method; the RenderBlocks render method of each render type that reads world metadata other than straight into getIcon(side, meta). **Not analysed**: other blocks, items and entities reading this block's metadata, tile-entity code and renderers (tile-entity blocks never get aliases), persistence.

Columns: **Creative stacks** are \`item:damage\` from native getSubBlocks (item damage, not world metadata); **Item-placed** are metadata values produced by onBlockPlaced from any item damage 0–15; **Unexecuted readers** counts metadata readers not executed conclusively (class-chain overrides, the render method, a tile entity; see JSON \`bytecode.unexecutedMetadataReaders\`); **Browser mapping** counts values with an exact, approximate (fallback) or no mapping in \`fromOriginal\` today (${bstat.exact} exact, ${bstat.approximate} approximate, ${bstat.none} none of ${total}). Placement across all values: ${place['creative-item']} reachable from Creative item damage, ${place['item-damage']} only from other item damage, ${place.none} not produced by item placement (they may still arise from world generation, updates or commands).

| Java block ID | Registry name | Creative stacks | Item-placed | Semantic | Alias (→canonical) | Invalid | Unclassified | Unexecuted readers | Browser mapping |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const research = new URL('../public/research/', import.meta.url);
  const reference = JSON.parse(await readFile(new URL('block-metadata-reference.json', research)));
  const {fromOriginal} = await import('../src/block-registry.js');
  await writeFile(new URL('block-metadata-catalogue.md', research), render(reference, browserStatus(fromOriginal)));
  console.log(`Wrote block metadata catalogue for ${reference.blocks.length} blocks.`);
}
