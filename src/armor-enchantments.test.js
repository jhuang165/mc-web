test("a bow release replays ItemBow.onPlayerStoppedUsing: Power, Punch, Flame, Infinity, the arrow and the bow's wear", () => {
  let shot = 0, infinite = 0, flamed = 0;
  for (const [bowStack, arrows, creative, ticks, seed, arrow, left, after] of reference.bow) {
    const s = new Survival({}, creative ? "creative" : "survival");
    s.inventory.main[0] = makeStack(BOW, 1, bowStack[1], undefined, bowStack[2].length ? { enchantments: ench(bowStack[2]) } : {});
    s.inventory.current = 0;
    if (arrows) s.inventory.main[1] = makeStack(ARROW, arrows);
    s.inventory.random = new JavaRandom(BigInt(seed));
    const made = releaseBow({ survival: s, arrows: new Arrows(() => 0.25), ticks, feet: { x: 10.5, y: 64, z: -3.5 }, yaw: 0.3, pitch: -0.2 });
    const row = JSON.stringify([bowStack, arrows, creative, ticks]);
    if (arrow === null) assert.equal(made, null, row);
    else {
      assert.ok(made, row);
      assert.deepEqual([made.damage, made.knockback, made.fire, made.pickup, made.crit], arrow, row);
      shot++;
      if (arrow[3] === 2 && !creative) infinite++;
      if (arrow[2]) flamed++;
    }
    const remaining = s.inventory.main.reduce((n, st) => n + (st?.id === ARROW ? st.count : 0), 0);
    assert.equal(remaining, left, row);
    assert.equal(s.inventory.main[0].damage, after[1], row);
  }
  assert.ok(shot > 200 && infinite > 10 && flamed > 10, JSON.stringify({ shot, infinite, flamed }));
});

