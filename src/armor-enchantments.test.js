test("a burning arrow sets the player on fire for 5 seconds (shortened by Fire Protection) and a mob shooter feels Thorns", () => {
  const arrows = new Arrows(() => 0.25), hits = [], shooter = { x: 5, y: 1, z: 5, type: "skeleton" };
  const guarded = wearer([[309, 0, [[1, 4]]], null, [299, 0, [[7, 10]]], null], 3);
  const mobs = { entities: [shooter], attackEntityFrom: (e, d, src) => (hits.push([d, src.name, src.player]), true) };
  const a = arrows.make({ x: 0, y: 0, z: 0, mx: 1, my: 0, mz: 0, yaw: 0, pitch: 0 }, new GaussianRandom(1), { shooter, fire: 100 });
  assert.equal(arrows.damageTarget(a, "player", 4, { survival: guarded, mobs, player: { x: 0, z: 0 } }), true);
  assert.equal(guarded.fire, 100 - Math.floor(f(f(100 * 4) * f(0.15))), "5 seconds = 100 ticks, 60 off");
  assert.equal(hits.length, 1, "Thorns X always rolls a hit");
  assert.ok(hits[0][0] >= 1 && hits[0][0] <= 4 && hits[0][1] === "thorns" && hits[0][2] === true);
});

