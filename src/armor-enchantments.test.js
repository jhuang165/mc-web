test("Thorns replays EnchantmentHelper.func_151384_a: rolls, damage, sound and the 3-or-1 durability cost", () => {
  let hits = 0, misses = 0, breaks = 0;
  for (const [before, seed, attackerLog, wearerLog, after, next] of reference.thorns) {
    const s = wearer(before, seed), got = [];
    s.thorns({ hurt: (d) => got.push(["thorns", d]), sound: () => got.push(["damage.thorns", 0.5, 1]) });
    const row = JSON.stringify([before, seed]);
    assert.deepEqual(got, attackerLog, row);
    assert.equal(s.inventory.random.nextInt(), next, "the wearer's Random is at the same point: " + row);
    let gone = 0;
    after.forEach((st, i) => {
      const live = s.inventory.armor[i];
      if (st === null) assert.equal(live, null, row);
      else if (live === null) { gone++; assert.equal(st[1], 0, "a broken piece natively resets to damage 0: " + row); }
      else assert.equal(live.damage, st[1], "armour slot " + i + " " + row);
    });
    assert.equal(gone, wearerLog.length, row);
    breaks += gone;
    if (attackerLog.length) hits++;
    else if (before.some((p) => p?.[2].some(([e, l]) => e === 7 && l > 0))) misses++;
  }
  assert.ok(hits > 40 && misses > 40 && breaks >= 3, JSON.stringify({ hits, misses, breaks }));
});

