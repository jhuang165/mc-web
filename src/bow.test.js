// The arrow hit, with a mob stand-in in the entity sweep.
function hitScene(arrow, ref, ctxExtra = {}) {
  const arrows = new Arrows(seeded(4)), world = worldFrom([[-50, 0, -50, 50, 9, 50, 1]]);
  const a = arrows.make({ x: 0.5, y: 12, z: 0.5, mx: 2.4, my: 0, mz: 0, yaw: 0, pitch: 0 }, new GaussianRandom(1), arrow);
  arrows.list.push(a);
  const damaged = [];
  const mobs = { entities: [ref], damage: (e, d, fx, fz, byPlayer) => (damaged.push([d, byPlayer]), true) };
  const target = { ref, box: [ref.x - 0.3, ref.y, ref.z - 0.3, ref.x + 0.3, ref.y + 1.8, ref.z + 0.3] };
  arrows.tick(world, { targets: arrowTargets([target], false), mobs, ...ctxExtra });
  return { a, arrows, damaged };
}

test("an arrow hitting a mob deals ceil(speed * damage), adds the crit bonus and is used up", () => {
  const ref = { x: 3.5, y: 11.5, z: 0.5, health: 20 };
  const { a, damaged, arrows } = hitScene({ damage: 2, shooter: "player" }, ref);
  assert.equal(a.dead, true);
  // Speed 2.4 * damage 2 = 4.8, rounded up.
  assert.deepEqual(damaged, [[5, true]]);
  assert.equal(arrows.list.length, 0);
  assert.equal(arrows.drain()[0].sound, "random.bowhit");
  const crit = hitScene({ damage: 2, shooter: "player", crit: true }, { x: 3.5, y: 11.5, z: 0.5, health: 20 });
  assert.ok(crit.damaged[0][0] >= 5 && crit.damaged[0][0] <= 5 + Math.floor(5 / 2) + 1, "a crit adds nextInt(dmg / 2 + 2)");
  const burning = { x: 3.5, y: 11.5, z: 0.5, health: 20 };
  hitScene({ damage: 2, shooter: "player", fire: 100 }, burning);
  assert.equal(burning.fire, 100, "a burning arrow sets the target alight for 5 seconds");
});

