test("EntityArrow.onUpdate: flight, water drag, sticking, the shake and the 1200 tick despawn", () => {
  const flights = cases("flight");
  assert.deepEqual(flights.map((c) => c.name), ["air", "air-fast", "air-lob", "water", "wall-x", "wall-slow", "floor", "despawn"]);
  for (const c of flights) {
    const arrows = new Arrows(seeded(3)), world = worldFrom(c.world),
      a = arrows.make({ x: c.from[0], y: c.from[1], z: c.from[2], mx: c.motion[0], my: c.motion[1], mz: c.motion[2], yaw: 0, pitch: 0 }, arrows.rng()),
      byTick = new Map(c.ticks.map((t) => [t.tick, t])), last = Math.max(...byTick.keys());
    arrows.list.push(a);
    for (let t = 1; t <= last; t++) {
      arrows.tick(world, {});
      const j = byTick.get(t);
      if (!j) continue;
      const what = `${c.name} tick ${t}`;
      for (const k of ["x", "y", "z", "mx", "my", "mz"]) near(a[k], j[k], 1e-9, `${what} ${k}`);
      assert.equal(a.yaw, f(j.yaw), `${what} yaw`);
      assert.equal(a.pitch, f(j.pitch), `${what} pitch`);
      assert.equal(a.prevYaw, f(j.prevYaw), `${what} prevYaw`);
      assert.equal(a.prevPitch, f(j.prevPitch), `${what} prevPitch`);
      assert.equal(a.inGround, j.inGround, `${what} inGround`);
      assert.equal(a.shake, j.shake, `${what} shake`);
      assert.equal(a.ticksInGround, j.ticksInGround, `${what} ticksInGround`);
      assert.equal(a.ticksInAir, j.ticksInAir, `${what} ticksInAir`);
      assert.equal(a.dead, j.dead, `${what} dead`);
      if (j.block >= 0) assert.deepEqual([a.xTile, a.yTile, a.zTile, a.inTile], [...j.tile, GAME[j.block]], `${what} tile`);
      // A dead arrow leaves the list, so the original's later ticks are not replayed.
      if (a.dead) break;
    }
  }
});

