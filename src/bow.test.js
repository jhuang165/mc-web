function tickShots(w, ticks, at = { x: 64.5, y: 0, z: 74.5 }) {
  const marks = [];
  let clock = 0;
  w.shoot = (mob, target, scale) => marks.push({ tick: clock, scale, d: Math.hypot(target.x - mob.x, target.z - mob.z) });
  for (; clock < ticks; clock++) w.tick({ ...at, health: 20 }, survival);
  return marks;
}

test("a skeleton with a target in range shoots on the ArrowAttack timer: 20 to 60 ticks apart, by distance", () => {
  const w = mobs([{ type: "skeleton", x: 64.5, y: 0, z: 64.5 }], () => 0.99);
  w.isDaytime = () => false;
  w.canSeeSky = () => false;
  const marks = tickShots(w, 400);
  assert.ok(marks.length >= 5, `shot ${marks.length} times`);
  for (let i = 1; i < marks.length; i++) {
    const gap = marks[i].tick - marks[i - 1].tick;
    assert.ok(gap >= 20 && gap <= 60, `gap ${gap}`);
  }
  for (const m of marks) {
    assert.ok(m.d <= 15.01, `shoots only within 15 blocks, was ${m.d}`);
    assert.ok(m.scale >= f(0.1) && m.scale <= 1);
    near(m.scale, rangeScale(f(f(m.d) / 15)), 0.02);
  }
});

