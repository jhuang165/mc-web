test("in daylight a skeleton restricts its paths to the shade and one on fire flees the sun", () => {
  const w = mobs([{ type: "skeleton", x: 64.5, y: 0, z: 64.5 }], () => 0.99), e = w.entities[0];
  w.isDaytime = () => true;
  w.canSeeSky = () => true;
  for (let i = 0; i < 12; i++) w.tick({ x: 64.5, y: 0, z: 150, health: 20 }, { ...survival, time: 100 });
  const brain = w.ai.brain(e);
  assert.equal(brain.navigator.noSunPath, true);
  const names = () => brain.tasks.running.map((r) => r.action.constructor.name);
  assert.ok(names().includes("RestrictSun"));
  e.fire = 300;
  w.canSeeSky = (x) => !(x > 66);
  const x0 = e.x;
  let fled = false;
  for (let i = 0; i < 30; i++) {
    w.tick({ x: 64.5, y: 0, z: 150, health: 20 }, { ...survival, time: 100 });
    if (names().includes("FleeSun")) fled = true;
  }
  assert.ok(fled, "the burning skeleton ran FleeSun");
  assert.ok(e.x > x0 + 1, "towards the shade at x > 66");
  // At night the sun task stops and the path restriction is lifted again.
  w.isDaytime = () => false;
  e.fire = 0;
  for (let i = 0; i < 40; i++) w.tick({ x: 64.5, y: 0, z: 150, health: 20 }, { ...survival, time: 15000 });
  assert.equal(brain.navigator.noSunPath, false);
});

