test("a skeleton's arrow matches the (world, shooter, target, velocity, inaccuracy) constructor", () => {
  const list = cases("mob");
  assert.ok(list.length >= 30);
  let skipped = 0;
  for (const c of list) {
    const shooter = { x: c.shooter[0], y: c.shooter[1], z: c.shooter[2], eyeHeight: f(f(c.shooter[3]) * f(0.85)) },
      target = { x: c.target[0], y: c.target[1], z: c.target[2], height: c.target[3] },
      h = mobArrow(new GaussianRandom(c.seed), shooter, target, c.velocity, c.inaccuracy);
    if (!h) {
      // Straight above or below: the constructor returns before setting anything.
      assert.deepEqual([c.x, c.z, c.mx, c.my, c.mz], [0, 0, 0, 0, 0]);
      skipped++;
      continue;
    }
    near(h.x, c.x, 1e-12, "x");
    near(h.y, c.y, 1e-12, "y");
    near(h.z, c.z, 1e-12, "z");
    near(h.mx, c.mx, 1e-12, "mx");
    near(h.my, c.my, 1e-12, "my");
    near(h.mz, c.mz, 1e-12, "mz");
    assert.equal(h.yaw, f(c.yaw));
    assert.equal(h.pitch, f(c.pitch));
    assert.equal(c.pickup, 0);
  }
  assert.equal(skipped, 1);
});

