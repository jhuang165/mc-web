// The probe's block ids (0 air, 1 stone, 9 water) as this game's ids (0, 3, 10).
const GAME = { 0: 0, 1: 3, 9: 10 };
function worldFrom(boxes) {
  const get = (x, y, z) => {
    let id = 0;
    for (const b of boxes) if (x >= b[0] && x <= b[3] && y >= b[1] && y <= b[4] && z >= b[2] && z <= b[5]) id = b[6];
    return GAME[id];
  };
  return { get, getMeta: () => 0, solid: (x, y, z) => get(x, y, z) === 3 };
}
