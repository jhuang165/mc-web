const pose = () => ({ progress: 0, item: 1, equip: 1, swing: swingPose(0), bob: bobPose(0, 0) });

test("the first-person bow transform stretches the bow along z by 1 + 0.2 * the pull", () => {
  const base = firstPersonMatrix(pose(), { bowDraw: 0 }), none = firstPersonMatrix(pose());
  assert.ok(base.elements.every(Number.isFinite));
  // bowDraw is ticks - 1 + partial; pull = (f * f + f * 2) / 3 for f = bowDraw / 20, at most 1.
  for (const draw of [5, 10, 19.5, 30]) {
    const pull = Math.min(1, ((draw / 20) ** 2 + (draw / 20) * 2) / 3), m = firstPersonMatrix(pose(), { bowDraw: draw });
    near(m.determinant() / base.determinant(), 1 + pull * 0.2, 1e-5, `draw ${draw}`);
  }
  assert.ok(Math.abs(none.determinant() - base.determinant()) < 1e-12, "the bow transform only rotates and translates at no pull");
  assert.notDeepEqual(Array.from(base.elements), Array.from(none.elements));
});

